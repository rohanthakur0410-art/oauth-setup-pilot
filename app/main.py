"""OAuth Setup Pilot - FastAPI app.

Routes:
  /                  library of pre-built, source-validated guides
  /guides/{slug}     a single guide page
  /api/generate      POST {query} -> run the investigation agent live
  /generated/{slug}  view a generated guide
  /healthz           health check
"""
import json
import logging
import os
import re
from pathlib import Path

from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import HTMLResponse, JSONResponse
from fastapi.staticfiles import StaticFiles
from fastapi.templating import Jinja2Templates
from pydantic import BaseModel

from .agent import investigate

BASE = Path(__file__).resolve().parent.parent
GUIDES_DIR = Path(os.environ.get("GUIDES_DIR", BASE / "guides"))
GENERATED_DIR = Path(os.environ.get("GENERATED_DIR", BASE / "generated"))
GENERATED_DIR.mkdir(exist_ok=True)

log = logging.getLogger("oauth-pilot")

app = FastAPI(title="OAuth Setup Pilot")
app.mount("/static", StaticFiles(directory=BASE / "app" / "static"), name="static")
templates = Jinja2Templates(directory=BASE / "app" / "templates")


def load_library() -> list[dict]:
    guides = []
    for f in sorted(GUIDES_DIR.glob("*.json")):
        guides.append(json.loads(f.read_text()))
    return guides


def load_guide(slug: str) -> dict | None:
    for d in (GUIDES_DIR, GENERATED_DIR):
        p = d / f"{slug}.json"
        if p.exists():
            return json.loads(p.read_text())
    return None


@app.get("/healthz")
def healthz():
    return {"ok": True, "llm_configured": bool(
        os.environ.get("GEMINI_API_KEY") or os.environ.get("OPENAI_API_KEY"))}


@app.get("/", response_class=HTMLResponse)
def index(request: Request):
    guides = load_library()
    return templates.TemplateResponse(request=request, name="index.html", context={"guides": guides})


@app.get("/guides/{slug}", response_class=HTMLResponse)
def guide_page(request: Request, slug: str):
    g = load_guide(slug)
    if not g:
        raise HTTPException(404, "guide not found")
    return templates.TemplateResponse(request=request, name="guide.html", context={"g": g})


def guide_markdown(g: dict) -> str:
    """Render a guide as a self-contained, shareable markdown document.
    Mirrors the on-screen 9-section structure."""
    ap = g["approval"]
    req = ap.get("requirement") or "unknown"
    basis = {"documented": "stated in official docs", "estimate": "estimate, not documented",
             "none": "no waiting period"}.get(ap.get("wait_basis"), "not established")
    L = [f"# {g['app_name']} - OAuth setup & approval guide", "",
         g["summary"], "",
         "## Ratings - four separate dimensions", "",
         f"- Setup difficulty: {g['difficulty']} - {g['difficulty_reason']}",
         f"- Hands-on effort: {g['setup_time']}",
         f"- Approval requirement: {req} ({ap.get('kind')})",
         f"- External wait: {ap['wait']} ({basis})",
         f"- Register at: {g['developer_console']}", ""]
    if ap.get("required") not in (True, False) or g.get("difficulty") == "unknown":
        L += ["> **Incomplete guide:** the fetched documentation did not establish key approval facts. Treat this as orientation, not a working setup recipe - verify the uncertainties before relying on it.", ""]
    if ap.get("notes"):
        L += [f"**Approval notes:** {ap['notes']}", ""]
    if g.get("requirements"):
        L += ["## Prerequisites & required permissions", ""] + [f"- {x}" for x in g["requirements"]] + [""]
    L.append("## Setup checklist")
    for i, s in enumerate(g["steps"], 1):
        src = f" ({s['source']})" if isinstance(s, dict) and s.get("source") else ""
        L += [f"{i}. [ ] **{s['title']}** - {s['detail']}{src}"]
    if g.get("nuances"):
        L += ["", "## Provider-specific nuances"] + [f"- {x}" for x in g["nuances"]]
    if g.get("common_blockers"):
        L += ["", "## Common blockers & solutions"]
        for x in g["common_blockers"]:
            if isinstance(x, dict):
                L.append(f"- **{x['problem']}**" + (f" Fix: {x['solution']}" if x.get("solution") else ""))
            else:
                L.append(f"- {x}")
    L += ["", "## Evidence, sources & uncertainties", ""]
    for e in g["evidence"]:
        L.append(f"- [{e['status']}] {e['claim']} ({e['source']})")
    if g.get("uncertainties"):
        L += ["", "### Unresolved uncertainties"] + [f"- {x}" for x in g["uncertainties"]]
    if g.get("sources_fetched"):
        L += ["", "### Pages the agent fetched"] + [f"- {u}" for u in g["sources_fetched"]]
    L += ["", "## What the agent can do vs what you must do", ""]
    for title, key in (("### Agent can do", "agent_can_do"), ("### You must do", "human_must_do")):
        if g.get(key):
            L += [title] + [f"- {x}" for x in g[key]] + [""]
    L += ["---", "Generated by OAuth Setup Pilot (Composio APM take-home). Claims are grounded in the cited sources; uncertainties are listed, not hidden."]
    return "\n".join(L) + "\n"


@app.get("/guides/{slug}/export")
def guide_export(slug: str):
    g = load_guide(slug)
    if not g:
        raise HTTPException(404, "guide not found")
    from fastapi.responses import PlainTextResponse
    return PlainTextResponse(
        guide_markdown(g),
        headers={"Content-Disposition": f'attachment; filename="{slug}-oauth-guide.md"'})


class GenRequest(BaseModel):
    query: str


# Minimal abuse guard for a public demo: per-IP generation allowance and a
# global concurrency cap so one visitor cannot burn the LLM budget.
import threading, time
_GEN_LOCK = threading.Lock()
_GEN_TIMES: dict[str, list[float]] = {}
_GEN_ACTIVE = 0
GEN_LIMIT = 5          # generations per window per IP
GEN_WINDOW = 600       # seconds
GEN_MAX_PARALLEL = 2


def _rate_check(ip: str) -> bool:
    now = time.time()
    with _GEN_LOCK:
        times = [t for t in _GEN_TIMES.get(ip, []) if now - t < GEN_WINDOW]
        if len(times) >= GEN_LIMIT:
            _GEN_TIMES[ip] = times
            return False
        times.append(now)
        _GEN_TIMES[ip] = times
        return True


@app.post("/api/generate")
def generate(req: GenRequest, request: Request):
    global _GEN_ACTIVE
    ip = request.client.host if request.client else "unknown"
    if not _rate_check(ip):
        return JSONResponse({"error": f"Rate limit: at most {GEN_LIMIT} generations per 10 minutes."}, status_code=429)
    with _GEN_LOCK:
        if _GEN_ACTIVE >= GEN_MAX_PARALLEL:
            return JSONResponse({"error": "Another investigation is running; try again in a minute."}, status_code=429)
        _GEN_ACTIVE += 1
    try:
        return _generate(req)
    finally:
        with _GEN_LOCK:
            _GEN_ACTIVE -= 1


def _generate(req: GenRequest):
    q = req.query.strip()
    if not q:
        raise HTTPException(400, "query required")
    if not re.match(r"^[\w .:/-]{2,120}$", q):
        raise HTTPException(400, "query has unsupported characters")
    try:
        guide = investigate(q)
    except RuntimeError as e:
        msg = str(e)
        if msg.startswith("LLM_UNAVAILABLE") or "not configured" in msg:
            # Provider-side failure: concise, no endpoints or internals.
            return JSONResponse({"error": "Couldn't generate the guide right now. Please try again."}, status_code=503)
        # Research-miss messages are already human-readable and safe.
        return JSONResponse({"error": msg}, status_code=503)
    except Exception:
        log.exception("investigation failed")
        return JSONResponse({"error": "Couldn't generate the guide right now. Please try again."}, status_code=500)
    (GENERATED_DIR / f"{guide['slug']}.json").write_text(json.dumps(guide, indent=2))
    return {"slug": guide["slug"], "url": f"/guides/{guide['slug']}", "guide": guide}
